'use strict'

// Pure logic for the sidebar gate: turn Antora's navigation tree and the sidebar
// Docusaurus built into the same ordered list of lines, then diff them. No I/O.
//
// A line is a node's full label path, plus its URL for a link:
//   "Upgrade › Using the Data Migration Tool › Overview  → /hazelcast/5.3/migrate/data-migration-tool"
// Path-qualified lines make a moved, re-nested, relabelled or re-ordered entry
// show up as a removed line plus an added one, without a tree-alignment step.
//
// The Antora side is put through the converter's DOCUMENTED sidebar transforms
// (converter/lib/nav buildPlan), each of which Docusaurus forces or the migration
// chose on purpose. Every entry a transform removes is returned, so the report
// shows what it cost rather than hiding it:
//   overview   an item with children becomes a category; its own page is the
//              category's first child, labelled "Overview"
//   collapse   a category whose only child is a parent page is merged with it
//   redirect   an entry for a page the migration withholds and redirects (a
//              dropped duplicate, duplicates.json) points at the redirect target
//   other      an entry for a page in another product is dropped (decided
//              2026-10-19; Platform 5.3's Operator link is the only one)
//   duplicate  a page is listed once; Antora's later listings of it (and the
//              subtree under a repeated parent) are dropped, as are categories
//              left empty. An autogenerated Docusaurus sidebar cannot list a doc
//              twice.

const { decodeHTML } = require('entities')
const { foldTypographic } = require('../../converter/lib/mdx')

// Visible text of a label. Antora's is HTML (`<code>`, entities, curly quotes);
// the converter folds curly quotes on purpose, so both sides are folded.
const text = (s) => foldTypographic(decodeHTML(String(s || '').replace(/<[^>]*>/g, ''))).replace(/\s+/g, ' ').trim()

// Antora publishes `/x/` or `/x.html`; Docusaurus has `trailingSlash: false`.
const normUrl = (u) => u.replace(/\.html(?=$|#)/, '').replace(/\/+(?=$|#)/, '')
const pageOf = (u) => normUrl(u).replace(/#.*$/, '')

const line = (trail, url) => trail.join(' › ') + (url ? `  → ${normUrl(url)}` : '')

// Antora menus -> { lines, duplicates, otherProduct }. `redirectOf(url)` gives
// the route a withheld page redirects to, or null; `isOwn(url)` says whether a
// URL is in this nav's own product.
function antoraLines (menus, redirectOf = () => null, isOwn = () => true) {
  const seen = new Set()
  const duplicates = []
  const otherProduct = []
  const lines = []
  const claim = (trail, url) => {
    if (seen.has(pageOf(url))) { duplicates.push(line(trail, url)); return false }
    seen.add(pageOf(url))
    return true
  }
  // Each emit returns the lines it produced, so a category can drop itself when
  // everything under it was a duplicate.
  const emitItems = (items, trail) => (items || []).flatMap((it) => emitItem(it, trail))
  const emitCategory = (t, body) => (body.length ? [line(t, null), ...body] : [])
  const emitItem = (raw, trail) => {
    const it = raw.url ? { ...raw, url: redirectOf(pageOf(raw.url)) || raw.url } : raw
    const t = [...trail, text(it.content)]
    const kids = it.items || []
    if (it.url && !isOwn(it.url)) { otherProduct.push(line(t, it.url)); return [] }
    if (!kids.length) {
      if (!it.url) return []
      return claim(t, it.url) ? [line(t, it.url)] : []
    }
    if (!it.url) return emitCategory(t, emitItems(kids, t))
    if (!claim(t, it.url)) return []
    return [line(t, null), line([...t, 'Overview'], it.url), ...emitItems(kids, t)]
  }
  for (const m of menus) {
    if (!m.content) { lines.push(...emitItems(m.items, [])); continue }
    const t = [text(m.content)]
    const only = m.items && m.items.length === 1 ? m.items[0] : null
    if (only && only.url && only.items && only.items.length) {
      const body = []
      if (claim(t, only.url)) body.push(line([...t, 'Overview'], only.url))
      body.push(...emitItems(only.items, t))
      lines.push(line(t, null), ...body)
    } else lines.push(...emitCategory(t, emitItems(m.items, t)))
  }
  return { lines, duplicates, otherProduct }
}

// Docusaurus sidebar items (version metadata `docsSidebars.<id>`) -> lines.
// `isUnlisted(item)` says whether a doc is `unlisted`; those are skipped, as a
// production build hides them.
function docusaurusLines (items, isUnlisted = () => false, trail = []) {
  const out = []
  for (const it of items || []) {
    if (it.unlisted || isUnlisted(it)) continue
    const t = [...trail, text(it.label)]
    if (it.type === 'category') {
      const body = docusaurusLines(it.items, isUnlisted, t)
      if (body.length || it.href) out.push(line(t, it.href || null), ...body)
    } else if (it.type === 'link') out.push(line(t, it.href))
  }
  return out
}

// URL of a line, or null for a category line.
const urlOf = (l) => { const i = l.indexOf('  → '); return i === -1 ? null : l.slice(i + 4) }

// Ordered diff (LCS). `removed`: in Antora, not in Docusaurus. `added`: the reverse.
function diffLines (a, b) {
  const n = a.length
  const m = b.length
  const L = Array.from({ length: n + 1 }, () => new Uint32Array(m + 1))
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) L[i][j] = a[i] === b[j] ? L[i + 1][j + 1] + 1 : Math.max(L[i + 1][j], L[i][j + 1])
  const removed = []
  const added = []
  let i = 0
  let j = 0
  while (i < n && j < m) {
    if (a[i] === b[j]) { i++; j++ } else if (L[i + 1][j] >= L[i][j + 1]) { removed.push(a[i++]) } else { added.push(b[j++]) }
  }
  while (i < n) removed.push(a[i++])
  while (j < m) added.push(b[j++])
  return { removed, added }
}

// Split Docusaurus-only lines into the expected ones (a page the orphan
// allowlist injects into this version's nav, `nav.after`) and the rest.
function splitInjected (added, injectedUrls) {
  const injected = []
  const rest = []
  for (const l of added) (urlOf(l) && injectedUrls.has(pageOf(urlOf(l))) ? injected : rest).push(l)
  return { injected, rest }
}

module.exports = { text, normUrl, pageOf, antoraLines, docusaurusLines, diffLines, splitInjected }
